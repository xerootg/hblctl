#[cfg(test)]
mod tests {
    use super::*;
    use hblctl_proto::{
        BusFrame, Sutest,
        bus::{BusHeader, NODE_EAGLE, NODE_TCP_HOST, SIGNAL_TEST_TX, TYPE_SUTEST},
    };
    use hblctl_transport::{
        capture::Direction,
        mock::{MockTransport, Step},
    };

    #[test]
    fn mock_session_invokes_refuses_validates_and_records_trace() {
        let dir = tempfile::tempdir().unwrap();
        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap();
        let (capture, log) = files(dir.path(), "mock", 30303, Safety::Read).unwrap();
        let registry = registry::builtin();
        let (command, func) = registry
            .operations()
            .find(|(_, f)| f.safety == hblctl_core::Safety::Read && f.request.is_empty())
            .unwrap();
        let request = Sutest::new(command.id, func.func, 1);
        let reply = BusFrame {
            header: BusHeader {
                signal: SIGNAL_TEST_TX,
                origin: NODE_EAGLE,
                dest: NODE_TCP_HOST,
                kind: TYPE_SUTEST,
            },
            record: request.clone(),
        }
        .encode_reply_message();
        let mock = MockTransport::new([
            Step::Expect(BusFrame::command(request).encode()),
            Step::Reply(reply),
        ]);
        let mut client = Client::new(Recording::new(mock, capture), Duration::from_secs(1), 1);
        tracing::dispatcher::with_default(&log, || {
            let result = run(
                &runtime,
                &mut client,
                Policy::default(),
                &command.name,
                &func.name,
                "{}",
            )
            .unwrap();
            assert_eq!(
                serde_json::from_str::<serde_json::Value>(&result).unwrap()["status"],
                "ok"
            );
            let (c, f) = registry
                .operations()
                .find(|(_, f)| f.safety > hblctl_core::Safety::Read)
                .unwrap();
            assert!(matches!(
                run(&runtime, &mut client, Policy::default(), &c.name, &f.name, "{}"),
                Err(Error::Refused { .. })
            ));
            assert!(matches!(
                run(
                    &runtime,
                    &mut client,
                    Policy::default(),
                    &command.name,
                    &func.name,
                    "[]"
                ),
                Err(Error::Arguments { .. })
            ));
            assert!(matches!(
                run(
                    &runtime,
                    &mut client,
                    Policy::default(),
                    &command.name,
                    &func.name,
                    r#"{"extra":1}"#
                ),
                Err(Error::Arguments { .. })
            ));
        });
        drop(client);
        let records = CaptureReader::new(File::open(dir.path().join("capture.hblcap")).unwrap())
            .unwrap()
            .records()
            .unwrap();
        assert_eq!(records.len(), 2);
        assert_eq!(records[0].direction, Direction::Sent);
        assert_eq!(records[1].direction, Direction::Received);
        assert!(
            dump(dir.path().join("capture.hblcap").to_string_lossy().into_owned())
                .unwrap()
                .iter()
                .any(|l| l.contains("frame signal="))
        );
        let events = fs::read_to_string(dir.path().join("events.jsonl")).unwrap();
        assert!(events.lines().any(|line| {
            let v: serde_json::Value = serde_json::from_str(line).unwrap();
            v["level"] == "TRACE" && v["target"] == "hblctl::wire"
        }));
        assert!(files(dir.path(), "mock", 30303, Safety::Read).is_err());
    }
    #[test]
    fn mock_connection_state_and_transport_failure() {
        let dir = tempfile::tempdir().unwrap();
        let (capture, log) = files(dir.path(), "mock", 30303, Safety::Read).unwrap();
        let session = Session {
            runtime: tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()
                .unwrap(),
            inner: Mutex::new(Inner {
                client: Some(Client::new(
                    Recording::new(Link::Mock(MockTransport::new([])), capture),
                    Duration::from_secs(1),
                    1,
                )),
            }),
            policy: Policy::default(),
            log,
            callback: Mutex::new(None),
        };
        assert!(session.is_connected().unwrap());
        let registry = registry::builtin();
        let (c, f) = registry
            .operations()
            .find(|(_, f)| f.safety > hblctl_core::Safety::Read)
            .unwrap();
        assert!(matches!(
            session.invoke(c.name.clone(), f.name.clone(), "{}".into()),
            Err(Error::Refused { .. })
        ));
        assert!(session.is_connected().unwrap());
        let (c, f) = registry
            .operations()
            .find(|(_, f)| f.safety == hblctl_core::Safety::Read && f.request.is_empty())
            .unwrap();
        assert!(matches!(
            session.invoke(c.name.clone(), f.name.clone(), "{}".into()),
            Err(Error::Transport { .. })
        ));
        assert!(!session.is_connected().unwrap());
        session.disconnect().unwrap();
        session.disconnect().unwrap();
    }
    #[test]
    fn registry_queries_share_desktop_schema() {
        let registry = Registry::new();
        let core = registry::builtin();
        for (c, f) in core.operations() {
            assert_eq!(
                registry.input_schema(c.name.clone(), f.name.clone()).unwrap(),
                registry::input_schema(f).to_string()
            );
        }
        assert!(registry.input_schema("missing".into(), "missing".into()).is_err());
    }
}
