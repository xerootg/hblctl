/// Maximum permitted effect on the camera.
#[derive(Clone, Copy, Debug, uniffi::Enum)]
pub enum Safety {
    /// Queries only.
    Read,
    /// Changes lost at restart.
    Volatile,
    /// Changes retained at restart.
    Persistent,
    /// Potentially irreversible changes.
    Destructive,
}
impl From<Safety> for hblctl_core::Safety {
    fn from(s: Safety) -> Self {
        match s {
            Safety::Read => Self::Read,
            Safety::Volatile => Self::Volatile,
            Safety::Persistent => Self::Persistent,
            Safety::Destructive => Self::Destructive,
        }
    }
}
/// Errors retain their category across the language boundary.
#[derive(Debug, thiserror::Error, uniffi::Error)]
pub enum Error {
    /// Policy prevented sending.
    #[error("refused: {message}")]
    Refused {
        /// Reason.
        message: String,
    },
    /// Invalid operation or arguments.
    #[error("arguments: {message}")]
    Arguments {
        /// Reason.
        message: String,
    },
    /// Connection or protocol failure.
    #[error("transport: {message}")]
    Transport {
        /// Reason.
        message: String,
    },
    /// Filesystem or runtime failure.
    #[error("session: {message}")]
    Session {
        /// Reason.
        message: String,
    },
}
fn session_error(e: impl std::fmt::Display) -> Error {
    Error::Session {
        message: e.to_string(),
    }
}
impl From<DispatchError> for Error {
    fn from(e: DispatchError) -> Self {
        let message = e.to_string();
        match e {
            DispatchError::Refused(_) => Self::Refused { message },
            DispatchError::Args(_) | DispatchError::Unknown(_) => Self::Arguments { message },
            DispatchError::Client(_) => Self::Transport { message },
        }
    }
}
/// Built-in registry and generated schemas.
#[derive(uniffi::Object)]
pub struct Registry {
    inner: registry::Registry,
}
#[uniffi::export]
impl Registry {
    /// Load the validated built-in registry.
    #[uniffi::constructor]
    #[must_use]
    pub fn new() -> Self {
        Self {
            inner: registry::builtin(),
        }
    }
    /// Commands, functions, safety, verified flags and documentation as JSON.
    ///
    /// # Panics
    /// Only if the registry cannot be serialized (all its fields are JSON-compatible).
    #[must_use]
    pub fn commands_json(&self) -> String {
        serde_json::to_string(&self.inner).expect("serializable registry")
    }
    /// Schema generated by the same function as the desktop frontends.
    pub fn input_schema(&self, command: String, func: String) -> Result<String, Error> {
        let f = self
            .inner
            .command(&command)
            .and_then(|c| c.func(&func))
            .ok_or_else(|| Error::Arguments {
                message: format!("unknown operation {command}.{func}"),
            })?;
        Ok(registry::input_schema(f).to_string())
    }
}
impl Default for Registry {
    fn default() -> Self {
        Self::new()
    }
}
/// Callback invoked outside session locks. Calls occur on the invoking worker thread.
#[uniffi::export(callback_interface)]
pub trait StatusCallback: Send + Sync {
    /// State or completed result JSON (including progress and notifications).
    fn status(&self, message: String);
}
type Camera<T> = Client<Recording<T, File>>;
enum Link {
    Tcp(TcpTransport),
    #[cfg(test)]
    Mock(hblctl_transport::mock::MockTransport),
}
impl Transport for Link {
    async fn send(&mut self, bytes: &[u8]) -> Result<(), hblctl_transport::Error> {
        match self {
            Self::Tcp(t) => t.send(bytes).await,
            #[cfg(test)]
            Self::Mock(t) => t.send(bytes).await,
        }
    }
    async fn recv(&mut self) -> Result<Option<Vec<u8>>, hblctl_transport::Error> {
        match self {
            Self::Tcp(t) => t.recv().await,
            #[cfg(test)]
            Self::Mock(t) => t.recv().await,
        }
    }
}
struct Inner {
    client: Option<Camera<Link>>,
}
/// One connection, runtime and recording. Calls are serialized.
#[derive(uniffi::Object)]
pub struct Session {
    runtime: tokio::runtime::Runtime,
    inner: Mutex<Inner>,
    policy: Policy,
    log: tracing::Dispatch,
    callback: Mutex<Option<Arc<dyn StatusCallback>>>,
}
fn files(
    dir: &Path,
    host: &str,
    port: u16,
    allow: Safety,
) -> Result<(CaptureWriter<File>, tracing::Dispatch), Error> {
    fs::create_dir_all(dir).map_err(session_error)?;
    let meta = serde_json::json!({"hblctl_version": env!("CARGO_PKG_VERSION"), "started_utc": time::OffsetDateTime::now_utc().format(&time::format_description::well_known::Rfc3339).map_err(session_error)?, "os": std::env::consts::OS, "arch": std::env::consts::ARCH, "argv": ["android", host], "port": port, "allow": format!("{allow:?}")});
    let create = |name| {
        File::options()
            .write(true)
            .create_new(true)
            .open(dir.join(name))
            .map_err(session_error)
    };
    create("meta.json")?
        .write_all(meta.to_string().as_bytes())
        .map_err(session_error)?;
    let event = create("events.jsonl")?;
    let log = tracing_subscriber::fmt()
        .json()
        .with_max_level(tracing::Level::TRACE)
        .with_writer(Mutex::new(event).with_max_level(tracing::Level::TRACE))
        .finish();
    Ok((
        CaptureWriter::new(create("capture.hblcap")?).map_err(session_error)?,
        tracing::Dispatch::new(log),
    ))
}
fn run<T: Transport + Send>(
    runtime: &tokio::runtime::Runtime,
    client: &mut Camera<T>,
    policy: Policy,
    command: &str,
    func: &str,
    args: &str,
) -> Result<String, Error> {
    let args: serde_json::Map<String, serde_json::Value> =
        serde_json::from_str(args).map_err(|e| Error::Arguments {
            message: e.to_string(),
        })?;
    runtime
        .block_on(dispatch::invoke(
            client,
            &registry::builtin(),
            policy,
            command,
            func,
            &args,
        ))
        .map(|v| v.to_string())
        .map_err(Into::into)
}
#[uniffi::export]
impl Session {
    /// Connect and create a fresh recording directory. Existing files are never overwritten.
    #[uniffi::constructor]
    pub fn connect(
        host: String,
        port: u16,
        timeout_ms: u64,
        allow: Safety,
        session_dir: String,
    ) -> Result<Self, Error> {
        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .map_err(session_error)?;
        let (capture, log) = files(Path::new(&session_dir), &host, port, allow)?;
        let timeout = Duration::from_millis(timeout_ms);
        let client = tracing::dispatcher::with_default(&log, || {
            tracing::info!(target: "hblctl::session", "connecting");
            runtime
                .block_on(TcpTransport::connect(&format!("{host}:{port}"), timeout, timeout))
                .map(|tcp| Client::new(Recording::new(Link::Tcp(tcp), capture), timeout, 1))
                .map_err(|e| Error::Transport {
                    message: e.to_string(),
                })
        })?;
        Ok(Self {
            runtime,
            inner: Mutex::new(Inner { client: Some(client) }),
            policy: Policy::up_to(allow.into()),
            log,
            callback: Mutex::new(None),
        })
    }
    /// Register or replace the status observer.
    pub fn set_status_callback(&self, callback: Box<dyn StatusCallback>) -> Result<(), Error> {
        *self.callback.lock().map_err(session_error)? = Some(Arc::from(callback));
        Ok(())
    }
    /// Invoke exclusively through shared dispatch. A transport failure closes the connection.
    pub fn invoke(&self, command: String, func: String, args_json: String) -> Result<String, Error> {
        let result = {
            let mut inner = self.inner.lock().map_err(session_error)?;
            let client = inner.client.as_mut().ok_or_else(|| Error::Transport {
                message: "disconnected".into(),
            })?;
            let result = tracing::dispatcher::with_default(&self.log, || {
                let result = run(&self.runtime, client, self.policy, &command, &func, &args_json);
                if let Err(error) = &result {
                    tracing::warn!(target: "hblctl::session", %command, %func, %error, "invocation failed");
                }
                result
            });
            if matches!(result, Err(Error::Transport { .. })) {
                inner.client = None;
            }
            result
        };
        self.notify(result.as_ref().map_or_else(ToString::to_string, Clone::clone));
        result
    }
    /// Close the socket and flush the capture.
    pub fn disconnect(&self) -> Result<(), Error> {
        self.inner.lock().map_err(session_error)?.client = None;
        tracing::dispatcher::with_default(&self.log, || {
            tracing::info!(target: "hblctl::session", "disconnected");
        });
        self.notify("disconnected".into());
        Ok(())
    }
    /// Last known connection state; peer closure is detected on invocation.
    pub fn is_connected(&self) -> Result<bool, Error> {
        Ok(self.inner.lock().map_err(session_error)?.client.is_some())
    }
}
impl Session {
    fn notify(&self, message: String) {
        let callback = self.callback.lock().ok().and_then(|c| c.clone());
        if let Some(callback) = callback {
            callback.status(message);
        }
    }
}
/// Decode captured chunks and reassemble protocol frames in both directions.
#[uniffi::export]
pub fn dump(path: String) -> Result<Vec<String>, Error> {
    let records = CaptureReader::new(File::open(path).map_err(session_error)?)
        .map_err(session_error)?
        .records()
        .map_err(session_error)?;
    Ok(dump::render(&records, true))
}
